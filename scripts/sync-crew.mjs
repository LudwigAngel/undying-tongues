// Copy the pure core and seed data into the Crew Scribes app so the app folder is
// self-contained (Kiro Crew installs it by copying that folder).
// `node scripts/sync-crew.mjs --check` fails if the copies drifted (used by the tests and a hook).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const FILES = [
  ['src/core/answer.js', 'crew-scribes/mcp/core/answer.js'],
  ['src/core/harvest.js', 'crew-scribes/mcp/core/harvest.js'],
  ['src/core/morph.js', 'crew-scribes/mcp/core/morph.js'],
  ['src/core/suggest.js', 'crew-scribes/mcp/core/suggest.js'],
  ['src/core/archive.js', 'crew-scribes/mcp/core/archive.js'],
  ['src/data/quechua.js', 'crew-scribes/mcp/data/quechua.js'],
];
const BANNER = '// GENERATED by scripts/sync-crew.mjs from the web app. Edit the original, then run npm run sync:crew.\n';

// git on Windows may check files out with CRLF; compare content, not line endings.
const lf = (s) => s.replace(/\r\n/g, '\n');

export function drift() {
  return FILES.filter(([src, dst]) => {
    const want = lf(BANNER + readFileSync(join(root, src), 'utf8'));
    return !existsSync(join(root, dst)) || lf(readFileSync(join(root, dst), 'utf8')) !== want;
  }).map(([, dst]) => dst);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const d = drift();
    if (d.length) { console.error(`out of sync: ${d.join(', ')} (run npm run sync:crew)`); process.exit(1); }
    console.log('crew-scribes core is in sync');
  } else {
    for (const [src, dst] of FILES) {
      mkdirSync(dirname(join(root, dst)), { recursive: true });
      writeFileSync(join(root, dst), BANNER + readFileSync(join(root, src), 'utf8'));
    }
    console.log(`synced ${FILES.length} files into crew-scribes/mcp`);
  }
}
